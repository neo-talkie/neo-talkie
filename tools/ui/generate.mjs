import { readFile, writeFile, mkdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root = new URL("../../", import.meta.url);
const read = (p) => readFile(new URL(p, root), "utf8");
const raw = await read("config/radio-ui/contract.json"),
  c = JSON.parse(raw);
const scenariosRaw = await read("config/radio-ui/scenarios.json");
const scenarios = JSON.parse(scenariosRaw, (key, value) =>
  value &&
  typeof value === "object" &&
  Object.keys(value).length === 1 &&
  value.copy
    ? (c.copy[value.copy] ??
      (() => {
        throw Error("Unknown fixture copy " + value.copy);
      })())
    : value,
);
if (c.schema !== "neotalkie-radio-ui-contract/v1")
  throw Error("Unknown contract schema");
const string = (k) => {
  if (typeof c.copy[k] !== "string") throw Error("Missing copy key " + k);
  return c.copy[k];
};
for (const s of Object.values(c.states)) string(s.label);
for (const k of [
  ...c.menu.map((f) => f.title),
  ...c.deviceMenu,
  ...c.services,
  ...c.checkErrors,
])
  string(k);
if (new Set(scenarios.map((s) => s.id)).size !== scenarios.length)
  throw Error("Duplicate scenario ID");
for (const s of scenarios) {
  for (const key of ["id", "name", "group", "note"])
    if (typeof s[key] !== "string" || !s[key])
      throw Error("Missing scenario " + key + ": " + s.id);
  if (s.phase && !c.states[s.phase])
    throw Error("Unknown scenario phase " + s.id);
  if (s.view && !c.views[s.view]) throw Error("Unknown scenario view " + s.id);
}
for (const phase of Object.keys(c.states))
  if (!scenarios.some((s) => s.phase === phase))
    throw Error("State lacks regression scenario: " + phase);
const coveredLabels = new Set(
  scenarios.map(
    (s) =>
      s.title ||
      (s.phase === "idle" || !s.phase
        ? s.hasContext
          ? c.copy.followup
          : c.copy.phase_idle
        : string(c.states[s.phase].label)),
  ),
);
for (let i = 0; i < c.menu.length; i++) {
  if (!scenarios.some((s) => s.view === "menu" && (s.selected || 0) === i))
    throw Error("Menu entry lacks simulator scenario: " + c.menu[i].id);
}
for (const key of c.nativeStates)
  if (!coveredLabels.has(string(key)))
    throw Error("Native state lacks a simulator scenario: " + key);
const hash = createHash("sha256")
  .update(raw)
  .update(scenariosRaw)
  .digest("hex");
const phases = Object.fromEntries(
  Object.entries(c.states).map(([k, s]) => [k, string(s.label)]),
);
const banner =
  "// GENERATED by tools/ui/generate.mjs. Edit config/radio-ui/*.json instead.\n";
const j = JSON.stringify;
let js = banner + `export const CONTRACT_HASH=${j(hash)};\n`;
for (const [name, value] of Object.entries({
  T: c.copy,
  L: c.layout,
  C: c.colors,
  MS: c.timing,
  PHASES: phases,
  STATE_META: c.states,
  NATIVE_STATES: c.nativeStates.map(string),
  VIEWS: c.views,
  MENU: c.menu.map((f) => ({ ...f, title: string(f.title) })),
  DEVICE_MENU: c.deviceMenu.map((title, i) => ({ id: c.menu[i].id, title: string(title) })),
  SERVICES: c.services.map(string),
  CHECK_ERRORS: c.checkErrors.map(string),
  EVENTS: c.events,
  GRAPHICS: c.graphics,
  SCENARIOS: scenarios,
  ANDROID_BASELINE: c.androidBaseline,
}))
  js += `export const ${name}=Object.freeze(${JSON.stringify(value, null, 2)});\n`;
js += `export function phaseForEvent(event){if(!Object.hasOwn(EVENTS,event))throw Error('Unknown UI event: '+event);return EVENTS[event];}\nexport function stateId(label){const id=Object.keys(PHASES).find(k=>PHASES[k]===label);if(!id)throw Error('Unknown UI state: '+label);return id;}\nexport function stage(phase){if(!STATE_META[phase])throw Error('Unknown UI phase: '+phase);return STATE_META[phase].stage;}\n`;
js += `export function menuSelection(index,direction){return Math.max(0,Math.min(MENU.length-1,index+direction));}\n`;
let java = banner + "package com.neotalkie.device;\n\nfinal class UiContract {\n";
java += `  static final String HASH=${j(hash)};\n`;
for (const [key, value] of Object.entries(c.copy))
  java += `  static final String T_${key.toUpperCase()}=${j(value)};\n`;
for (const [key, value] of Object.entries(c.layout))
  java += `  static final int ${key}=${value};\n`;
for (const [key, value] of Object.entries(c.colors))
  java += `  static final int C_${key}=0xff${value.slice(1)};\n`;
for (const [key, value] of Object.entries(c.timing))
  java += `  static final int ${key}=${value};\n`;
for (const [name, list] of Object.entries({
  MENU: c.menu.map((f) => f.title),
  DEVICE_MENU: c.deviceMenu,
  SERVICES: c.services,
}))
  java += `  static final String[] ${name}={${list.map((k) => "T_" + k.toUpperCase()).join(",")}};\n`;
c.menu.forEach((f, i) => {
  java += `  static final int MENU_${f.id.toUpperCase()}=${i};\n`;
});
java += `  static int menuSelection(int index,int direction) { return Math.max(0,Math.min(MENU.length-1,index+direction)); }\n`;
java += `  static final int[][] PAGE_ARROWS={${c.graphics.pageArrows.map((r) => "{" + r.join(",") + "}").join(",")}};\n`;
java += `  static final int[][] DIGITS={${c.graphics.digits.map((r) => "{" + r.join(",") + "}").join(",")}};\n  static final int[] BOLT={${c.graphics.bolt.join(",")}};\n`;
java += "  static String phaseForEvent(String event) {\n    switch(event) {\n";
for (const [event, id] of Object.entries(c.events)) {
  if (!c.states[id]) throw Error("Unknown event target " + id);
  java += `      case ${j(event)}: return ${j(id)};\n`;
}
java +=
  '      default: throw new IllegalArgumentException("Unknown UI event: "+event);\n    }\n  }\n';
java += "  static String label(String id) {\n    switch(id) {\n";
for (const [id, s] of Object.entries(c.states))
  java += `      case ${j(id)}: return T_${s.label.toUpperCase()};\n`;
java +=
  '      default: throw new IllegalArgumentException("Unknown UI state: "+id);\n    }\n  }\n';
java += "  static int stage(String label) {\n";
for (const s of Object.values(c.states))
  if (s.stage)
    java += `    if(label.equals(T_${s.label.toUpperCase()}))return ${s.stage};\n`;
java += "    return 0;\n  }\n";
java += "  static String requireState(String label) {\n";
for (const key of c.nativeStates)
  java += `    if(T_${key.toUpperCase()}.equals(label))return label;\n`;
java +=
  '    throw new IllegalArgumentException("Unregistered UI state: "+label);\n  }\n  static String eventLabel(String event) { return label(phaseForEvent(event)); }\n}\n';
const outputs = {
  "android/common/src/com/neotalkie/device/UiContract.java": java,
  "tools/simulator/generated/ui-contract.js": js,
};
for (const [path, value] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if ((await read(path).catch(() => null)) !== value)
      throw Error(
        "Generated file is stale: " + path + "; run make ui-generate",
      );
  } else {
    await mkdir(new URL(".", new URL(path, root)), { recursive: true });
    await writeFile(new URL(path, root), value);
  }
}
console.log(
  `UI contract ${hash.slice(0, 12)} · ${Object.keys(c.states).length} phases · ${scenarios.length} scenarios${process.argv.includes("--check") ? " checked" : " generated"}`,
);
